// Command configref writes the configuration reference (docs/reference/configuration.md) from
// the Go source of the config schema: YAML keys come from struct tags and descriptions from the
// field comments, so the reference cannot drift from the code.
//
//	go run ./tools/configref > docs/reference/configuration.md
//
// `scripts/docker-check.sh docs` fails when the committed file is out of date.
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

// Packages whose struct types can appear in the config, keyed by package name.
var sources = map[string]string{
	"config":    "pkg/config",
	"transform": "pkg/transform",
}

type field struct {
	key, typ, doc string
	nested        string // qualified struct type name to recurse into, if any
	repeated      bool   // slice of structs
	mapOf         bool   // map with struct values
}

type structInfo struct {
	doc    string
	fields []field
}

var structs = map[string]structInfo{} // "config.ServerConfig" -> fields

func main() {
	for pkgName, dir := range sources {
		if err := load(pkgName, dir); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}

	var b strings.Builder
	b.WriteString("# Configuration reference\n\n")
	b.WriteString("<!-- Generated by `go run ./tools/configref` from pkg/config. Do not edit by hand. -->\n\n")
	b.WriteString("Every key Odin reads from its YAML configuration file. Keys not listed here are ignored.\n")
	b.WriteString("Durations are written like `30s`, `5m` or `1h30m`. Any value can come from the environment as\n")
	b.WriteString("`${NAME}` (required) or `${NAME:-default}`. Services can also live in a `services.yaml` next to\n")
	b.WriteString("the main file. For a guided introduction see [Concepts](../concepts.md).\n\n")

	root := structs["config.Config"]
	for _, f := range root.fields {
		b.WriteString("## `" + f.key + "`\n\n")
		if f.doc != "" {
			b.WriteString(f.doc + "\n\n")
		}
		if d := structs[f.nested].doc; d != "" {
			b.WriteString(d + "\n\n")
		}
		rows := [][3]string{}
		prefix := f.key
		if f.repeated {
			prefix += "[]"
		}
		collect(f.nested, prefix, &rows, map[string]bool{})
		if len(rows) == 0 {
			continue
		}
		b.WriteString("| Key | Type | Description |\n| --- | --- | --- |\n")
		for _, r := range rows {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", r[0], r[1], r[2])
		}
		b.WriteString("\n")
	}
	fmt.Print(b.String())
}

func collect(typeName, prefix string, rows *[][3]string, seen map[string]bool) {
	info, ok := structs[typeName]
	if !ok || seen[typeName] {
		return
	}
	seen[typeName] = true
	defer delete(seen, typeName)

	for _, f := range info.fields {
		key := prefix + "." + f.key
		if f.nested != "" {
			typ := "object"
			switch {
			case f.repeated:
				typ = "list of objects"
				key += "[]"
			case f.mapOf:
				typ = "map of objects"
				key += ".<name>"
			}
			if f.doc != "" || f.repeated || f.mapOf {
				*rows = append(*rows, [3]string{strings.TrimSuffix(strings.TrimSuffix(key, "[]"), ".<name>"), typ, f.doc})
			}
			collect(f.nested, key, rows, seen)
			continue
		}
		*rows = append(*rows, [3]string{key, f.typ, f.doc})
	}
}

func load(pkgName, dir string) error {
	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return err
	}
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				doc := ts.Doc
				if doc == nil {
					doc = gen.Doc
				}
				structs[pkgName+"."+ts.Name.Name] = structInfo{doc: typeDoc(doc, ts.Name.Name), fields: fields(pkgName, st)}
			}
		}
	}
	return nil
}

func fields(pkgName string, st *ast.StructType) []field {
	var out []field
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 || f.Tag == nil {
			continue
		}
		tag, err := strconv.Unquote(f.Tag.Value)
		if err != nil {
			continue
		}
		key := strings.Split(reflect.StructTag(tag).Get("yaml"), ",")[0]
		if key == "" || key == "-" {
			continue
		}
		fd := field{key: key, doc: comment(f)}
		fd.typ, fd.nested, fd.repeated, fd.mapOf = describe(pkgName, f.Type)
		out = append(out, fd)
	}
	return out
}

// describe turns a field type into a readable name, and the struct to document underneath.
func describe(pkgName string, expr ast.Expr) (typ, nested string, repeated, mapOf bool) {
	switch t := expr.(type) {
	case *ast.StarExpr:
		return describe(pkgName, t.X)
	case *ast.ArrayType:
		inner, n, _, _ := describe(pkgName, t.Elt)
		if n != "" {
			return "list", n, true, false
		}
		return "list of " + inner, "", false, false
	case *ast.MapType:
		k, _, _, _ := describe(pkgName, t.Key)
		v, n, _, _ := describe(pkgName, t.Value)
		if n != "" {
			return "map", n, false, true
		}
		return fmt.Sprintf("map of %s to %s", k, v), "", false, false
	case *ast.SelectorExpr:
		pkg, _ := t.X.(*ast.Ident)
		if pkg != nil && pkg.Name == "time" && t.Sel.Name == "Duration" {
			return "duration", "", false, false
		}
		if pkg != nil {
			if _, ok := sources[pkg.Name]; ok {
				return "object", pkg.Name + "." + t.Sel.Name, false, false
			}
		}
		return t.Sel.Name, "", false, false
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "string", "", false, false
		case "bool":
			return "boolean", "", false, false
		case "int", "int32", "int64", "uint32", "uint64":
			return "integer", "", false, false
		case "float64":
			return "number", "", false, false
		}
		if _, ok := structs[pkgName+"."+t.Name]; ok || ast.IsExported(t.Name) {
			return "object", pkgName + "." + t.Name, false, false
		}
		return t.Name, "", false, false
	case *ast.InterfaceType:
		return "any", "", false, false
	}
	return "value", "", false, false
}

func comment(f *ast.Field) string {
	var parts []string
	if f.Doc != nil {
		parts = append(parts, f.Doc.Text())
	}
	if f.Comment != nil {
		parts = append(parts, f.Comment.Text())
	}
	text := strings.Join(strings.Fields(strings.Join(parts, " ")), " ")
	return strings.ReplaceAll(text, "|", "\\|")
}

// typeDoc keeps a type's doc comment unless it only restates the name.
func typeDoc(cg *ast.CommentGroup, name string) string {
	if cg == nil {
		return ""
	}
	text := strings.Join(strings.Fields(cg.Text()), " ")
	words := strings.Fields(text)
	if len(words) <= 6 && len(words) > 0 && words[0] == name {
		return ""
	}
	return text
}

